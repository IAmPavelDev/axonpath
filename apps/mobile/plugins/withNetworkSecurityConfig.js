/**
 * Bundles the axon-beta CA into the Android build and scopes trust for the
 * static-IP API host to it (Android Network Security Config). Pair with
 * deploy/generate-certs.sh, which produces apps/mobile/ca/axon-ca.crt.
 *
 * app.json: ["./plugins/withNetworkSecurityConfig", { "ip": "<STATIC_IP>" }]
 *
 * Docs: https://developer.android.com/privacy-and-security/security-config
 * Note: once NSC exists, the usesCleartextTraffic manifest flag is ignored —
 * the NSC base-config keeps cleartext enabled for the emulator dev flow.
 */
const { withAndroidManifest, withDangerousMod } = require("@expo/config-plugins");
const fs = require("node:fs");
const path = require("node:path");

const NSC_XML = (ip) => `<?xml version="1.0" encoding="utf-8"?>
<network-security-config>
    <!-- Dev keeps cleartext (emulator http://10.0.2.2:3001). The production
         API host (${ip}) additionally trusts the bundled axon-beta CA. -->
    <base-config cleartextTrafficPermitted="true">
        <trust-anchors>
            <certificates src="system" />
        </trust-anchors>
    </base-config>
    <domain-config>
        <domain>${ip}</domain>
        <trust-anchors>
            <certificates src="@raw/axon_ca" />
            <certificates src="system" />
        </trust-anchors>
    </domain-config>
</network-security-config>
`;

const withNetworkSecurityConfig = (config, props = {}) => {
  const ip = props.ip;
  if (!ip) {
    throw new Error(
      "withNetworkSecurityConfig: missing `ip` — set your static server IP in app.json plugins",
    );
  }

  // The CA is public material, generated by deploy/generate-certs.sh and
  // committed. Skip cleanly (local prebuilds before cert generation) instead
  // of half-applying: manifest attr without the XML resource would break AAPT.
  const caSource = path.join(__dirname, "..", "ca", "axon-ca.crt");
  if (!fs.existsSync(caSource)) {
    console.warn(
      "[withNetworkSecurityConfig] apps/mobile/ca/axon-ca.crt not found — " +
        "run `./deploy/generate-certs.sh <STATIC_IP>` first. Skipping NSC.",
    );
    return config;
  }

  config = withAndroidManifest(config, (mod) => {
    const application = mod.modResults.manifest.application?.[0];
    if (application) {
      application.$["android:networkSecurityConfig"] =
        "@xml/network_security_config";
    }
    return mod;
  });

  config = withDangerousMod(config, [
    "android",
    (mod) => {
      const resDir = path.join(
        mod.modRequest.platformProjectRoot,
        "app",
        "src",
        "main",
        "res",
      );
      const xmlDir = path.join(resDir, "xml");
      const rawDir = path.join(resDir, "raw");
      fs.mkdirSync(xmlDir, { recursive: true });
      fs.mkdirSync(rawDir, { recursive: true });

      fs.writeFileSync(
        path.join(xmlDir, "network_security_config.xml"),
        NSC_XML(ip),
      );
      fs.copyFileSync(caSource, path.join(rawDir, "axon_ca.crt"));
      return mod;
    },
  ]);

  return config;
};

module.exports = withNetworkSecurityConfig;
