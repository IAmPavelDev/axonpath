import type { Result } from "@/modules/platform/result";

/** One probe step: timing + transport outcome, never throws upstream. */
export type ScrapeStep = {
  ok: boolean;
  latencyMs: number;
  httpStatus: number | null;
  detail: string | null;
};

export type YouTubeSearchHit = {
  videoId: string;
  title: string;
  channel: string;
  durationSeconds: number | null;
  viewCountText: string | null;
};

export type CaptionTrack = {
  baseUrl: string;
  languageCode: string;
  isAutoGenerated: boolean;
};

export type WatchPageMeta = {
  playabilityStatus: string | null;
  playabilityReason: string | null;
  title: string | null;
  durationSeconds: number | null;
  innertubeApiKey: string | null;
  innertubeClientVersion: string | null;
  captionTracks: CaptionTrack[];
};

export type TranscriptSegment = {
  startSeconds: number;
  endSeconds: number | null;
  text: string;
};

export type TranscriptSample = { startSeconds: number; text: string };

export type YouTubeAccessReport = {
  ranAt: Date;
  egressIp: string | null;
  search: ScrapeStep & {
    query: string;
    resultCount: number;
    topResults: YouTubeSearchHit[];
  };
  watchPage: ScrapeStep & {
    videoId: string;
    playabilityStatus: string | null;
    playabilityReason: string | null;
    title: string | null;
    durationSeconds: number | null;
  };
  transcript: ScrapeStep & {
    videoId: string;
    language: string | null;
    isAutoGenerated: boolean | null;
    segmentCount: number;
    samples: TranscriptSample[];
  };
  verdict: string;
};

export type ScrapeError = {
  kind: "HttpRequestFailed" | "ParseFailed";
  detail: string;
  httpStatus?: number;
};

/** The raw, dependency-free YouTube access surface the probe measures. */
export type YouTubeScraperPort = {
  /** Public egress IP of the runtime (Lambda: AWS range) — null when unresolvable. */
  fetchEgressIp(): Promise<string | null>;
  fetchWatchPage(videoId: string): Promise<Result<WatchPageMeta, ScrapeError>>;
  searchYouTube(
    query: string,
    context: { innertubeApiKey: string | null; innertubeClientVersion: string | null },
  ): Promise<Result<YouTubeSearchHit[], ScrapeError>>;
  /**
   * Full transcript pass for one video via the ANDROID InnerTube player:
   * the WEB watch-page timedtext URLs return empty bodies (2024+ protection),
   * the ANDROID player's caption URLs serve real tracks.
   */
  fetchTranscript(
    videoId: string,
  ): Promise<Result<TranscriptOutcome, ScrapeError>>;
};

export type TranscriptOutcome = {
  language: string | null;
  isAutoGenerated: boolean | null;
  segments: TranscriptSegment[];
};
