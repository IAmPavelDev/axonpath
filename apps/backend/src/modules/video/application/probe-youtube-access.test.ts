import { describe, expect, it } from "vitest";

import type { Clock } from "@/modules/platform/ports/clock";
import {
  makeProbeYoutubeAccess,
  type ProbeYouTubeAccessDeps,
} from "@/modules/video/application/probe-youtube-access";
import type {
  ScrapeError,
  TranscriptOutcome,
  TranscriptSegment,
  WatchPageMeta,
  YouTubeScraperPort,
  YouTubeSearchHit,
} from "@/modules/video/domain/youtube-access";

const CLOCK: Clock = { now: () => new Date("2026-10-12T12:00:00Z") };
const DEFAULT_VIDEO = "jNQXAC9IVRw";

const WATCH_META = (): WatchPageMeta => ({
  playabilityStatus: "OK",
  playabilityReason: null,
  title: "Closures explained",
  durationSeconds: 600,
  innertubeApiKey: "AIzaSyFAKE",
  innertubeClientVersion: "2.20261001.00.00",
  captionTracks: [
    { baseUrl: "https://timedtext/web-en", languageCode: "en", isAutoGenerated: false },
  ],
});

const HIT = (videoId: string): YouTubeSearchHit => ({
  videoId,
  title: `video ${videoId}`,
  channel: "Edu Channel",
  durationSeconds: 300,
  viewCountText: "1M views",
});

const SEGMENTS = (count: number): TranscriptSegment[] =>
  Array.from({ length: count }, (_, i) => ({
    startSeconds: i * 5,
    endSeconds: i * 5 + 5,
    text: `segment ${i}`,
  }));

const TRANSCRIPT_OK = (): TranscriptOutcome => ({
  language: "en",
  isAutoGenerated: true,
  segments: SEGMENTS(3),
});

type ScriptedScraper = YouTubeScraperPort & {
  searchQueries: string[];
  transcriptVideoIds: string[];
};

const makeScriptedScraper = (options: {
  egressIp?: string | null;
  watchPage?: { ok: true; value: WatchPageMeta } | { ok: false; error: ScrapeError };
  search?: { ok: true; value: YouTubeSearchHit[] } | { ok: false; error: ScrapeError };
  transcript?: { ok: true; value: TranscriptOutcome } | { ok: false; error: ScrapeError };
}): ScriptedScraper => {
  const calls = {
    searchQueries: [] as string[],
    transcriptVideoIds: [] as string[],
  };
  return {
    searchQueries: calls.searchQueries,
    transcriptVideoIds: calls.transcriptVideoIds,
    fetchEgressIp: async () => options.egressIp ?? null,
    fetchWatchPage: async () => {
      if (!options.watchPage) throw new Error("unexpected fetchWatchPage call");
      return options.watchPage;
    },
    searchYouTube: async (query) => {
      calls.searchQueries.push(query);
      if (!options.search) throw new Error("unexpected searchYouTube call");
      return options.search;
    },
    fetchTranscript: async (videoId) => {
      calls.transcriptVideoIds.push(videoId);
      if (!options.transcript) throw new Error("unexpected fetchTranscript call");
      return options.transcript;
    },
  };
};

const makeDeps = (scraper: ScriptedScraper): ProbeYouTubeAccessDeps => ({
  scraper,
  clock: CLOCK,
});

describe("makeProbeYoutubeAccess", () => {
  it("reports a fully operational path when every step succeeds", async () => {
    const scraper = makeScriptedScraper({
      egressIp: "10.0.0.1",
      watchPage: { ok: true, value: WATCH_META() },
      search: { ok: true, value: [HIT("abc12345678"), HIT("def23456789")] },
      transcript: { ok: true, value: TRANSCRIPT_OK() },
    });

    const report = await makeProbeYoutubeAccess(makeDeps(scraper))({
      query: "closures",
      videoId: null,
    });

    expect(report.verdict).toContain("UNOFFICIAL PATH OPERATIONAL");
    expect(report.ranAt.toISOString()).toBe("2026-10-12T12:00:00.000Z");
    expect(report.egressIp).toBe("10.0.0.1");
    expect(report.search.resultCount).toBe(2);
    expect(report.search.topResults).toHaveLength(2);
    expect(report.watchPage.ok).toBe(true);
    expect(report.watchPage.playabilityStatus).toBe("OK");
    expect(report.transcript.ok).toBe(true);
    expect(report.transcript.segmentCount).toBe(3);
    expect(report.transcript.samples).toHaveLength(3);
    expect(report.transcript.language).toBe("en");
    expect(report.transcript.isAutoGenerated).toBe(true);
    // Transcript pass targets the probed video through the ANDROID player.
    expect(scraper.transcriptVideoIds).toEqual([DEFAULT_VIDEO]);
  });

  it("flags a bot wall while still probing search and transcript", async () => {
    const scraper = makeScriptedScraper({
      watchPage: {
        ok: true,
        value: {
          ...WATCH_META(),
          playabilityStatus: "LOGIN_REQUIRED",
          playabilityReason: "Sign in to confirm you're not a bot",
        },
      },
      search: { ok: true, value: [HIT("abc12345678")] },
      transcript: { ok: true, value: TRANSCRIPT_OK() },
    });

    const report = await makeProbeYoutubeAccess(makeDeps(scraper))({
      query: "closures",
      videoId: null,
    });

    expect(report.verdict).toContain("DEGRADED");
    expect(report.watchPage.playabilityStatus).toBe("LOGIN_REQUIRED");
    expect(scraper.searchQueries).toEqual(["closures"]);
    expect(report.transcript.ok).toBe(true);
  });

  it("keeps search and transcript independent when the watch page is unreachable", async () => {
    const scraper = makeScriptedScraper({
      watchPage: {
        ok: false,
        error: { kind: "ParseFailed", detail: "consent interstitial", httpStatus: 200 },
      },
      search: { ok: true, value: [HIT("abc12345678")] },
      transcript: { ok: true, value: TRANSCRIPT_OK() },
    });

    const report = await makeProbeYoutubeAccess(makeDeps(scraper))({
      query: "closures",
      videoId: null,
    });

    expect(report.watchPage.ok).toBe(false);
    expect(report.watchPage.detail).toBe("consent interstitial");
    // Search ran keyless (no INNERTUBE context available) and still succeeded.
    expect(report.search.ok).toBe(true);
    // Transcript rides the ANDROID player — independent of the watch page.
    expect(report.transcript.ok).toBe(true);
    expect(scraper.transcriptVideoIds).toEqual([DEFAULT_VIDEO]);
    expect(report.verdict).toContain("DEGRADED");
  });

  it("degrades the search and transcript steps on request failures", async () => {
    const scraper = makeScriptedScraper({
      watchPage: { ok: true, value: WATCH_META() },
      search: {
        ok: false,
        error: { kind: "HttpRequestFailed", detail: "search HTTP 403", httpStatus: 403 },
      },
      transcript: {
        ok: false,
        error: { kind: "HttpRequestFailed", detail: "timedtext HTTP 403", httpStatus: 403 },
      },
    });

    const report = await makeProbeYoutubeAccess(makeDeps(scraper))({
      query: "closures",
      videoId: "jNQXAC9IVRw",
    });

    expect(report.search.ok).toBe(false);
    expect(report.search.detail).toBe("search HTTP 403");
    expect(report.transcript.ok).toBe(false);
    expect(report.transcript.httpStatus).toBe(403);
    expect(report.transcript.language).toBeNull();
    expect(report.transcript.isAutoGenerated).toBeNull();
    expect(report.verdict).toContain("DEGRADED");
  });
});
