import type {
  TranscriptSegment,
  YouTubeAccessReport,
  YouTubeScraperPort,
} from "@/modules/video/domain/youtube-access";
import type { Clock } from "@/modules/platform/ports/clock";

export type ProbeYouTubeAccessDeps = {
  scraper: YouTubeScraperPort;
  clock: Clock;
};

export type ProbeYouTubeAccessInput = {
  query: string;
  videoId?: string | null;
};

/** Canonical public video ("Me at the zoo") when the caller pins no target. */
const PROBE_FALLBACK_VIDEO_ID = "jNQXAC9IVRw";

/**
 * Probe the unofficial YouTube paths from the current runtime and report each
 * step's outcome independently. Never throws: every failure lands in the step
 * it belongs to, so one blocked endpoint never hides the others. The report is
 * the experiment's result — deployed to Lambda it answers whether AWS egress
 * IPs pass the watch page, InnerTube search, and timedtext.
 */
export const makeProbeYoutubeAccess =
  ({ scraper, clock }: ProbeYouTubeAccessDeps) =>
  async (input: ProbeYouTubeAccessInput): Promise<YouTubeAccessReport> => {
    const ranAt = clock.now();
    const targetVideoId = input.videoId ?? PROBE_FALLBACK_VIDEO_ID;

    const watchStarted = performance.now();
    const [egressIp, watchPageResult] = await Promise.all([
      scraper.fetchEgressIp(),
      scraper.fetchWatchPage(targetVideoId),
    ]);
    const watchLatency = Math.round(performance.now() - watchStarted);

    const watchStep =
      watchPageResult.ok
        ? {
            ok: true,
            latencyMs: watchLatency,
            httpStatus: 200,
            detail: null,
            videoId: targetVideoId,
            playabilityStatus: watchPageResult.value.playabilityStatus,
            playabilityReason: watchPageResult.value.playabilityReason,
            title: watchPageResult.value.title,
            durationSeconds: watchPageResult.value.durationSeconds,
          }
        : {
            ok: false,
            latencyMs: watchLatency,
            httpStatus: watchPageResult.error.httpStatus ?? null,
            detail: watchPageResult.error.detail,
            videoId: targetVideoId,
            playabilityStatus: null,
            playabilityReason: null,
            title: null,
            durationSeconds: null,
          };

    const searchStarted = performance.now();
    const searchResult = await scraper.searchYouTube(input.query, {
      innertubeApiKey: watchPageResult.ok
        ? watchPageResult.value.innertubeApiKey
        : null,
      innertubeClientVersion: watchPageResult.ok
        ? watchPageResult.value.innertubeClientVersion
        : null,
    });
    const searchLatency = Math.round(performance.now() - searchStarted);

    const searchStep = {
      ok: searchResult.ok,
      latencyMs: searchLatency,
      httpStatus: searchResult.ok
        ? 200
        : (searchResult.error.httpStatus ?? null),
      detail: searchResult.ok ? null : searchResult.error.detail,
      query: input.query,
      resultCount: searchResult.ok ? searchResult.value.length : 0,
      topResults: searchResult.ok ? searchResult.value.slice(0, 10) : [],
    };

    const transcriptStarted = performance.now();
    const transcriptResult = await scraper.fetchTranscript(targetVideoId);
    const transcriptLatency = Math.round(
      performance.now() - transcriptStarted,
    );

    // The transcript pass rides the ANDROID player client and is fully
    // independent of the WEB watch page — one wall never hides the other.
    const transcriptOutcome = transcriptResult.ok
      ? {
          ok: true as const,
          latencyMs: transcriptLatency,
          httpStatus: 200 as number | null,
          detail: null as string | null,
          language: transcriptResult.value.language,
          isAutoGenerated: transcriptResult.value.isAutoGenerated,
          segments: transcriptResult.value.segments,
        }
      : {
          ok: false as const,
          latencyMs: transcriptLatency,
          httpStatus: transcriptResult.error.httpStatus ?? null,
          detail: transcriptResult.error.detail,
          language: null,
          isAutoGenerated: null,
          segments: [] as TranscriptSegment[],
        };

    const transcriptStep = {
      ok: transcriptOutcome.ok,
      latencyMs: transcriptOutcome.latencyMs,
      httpStatus: transcriptOutcome.httpStatus,
      detail: transcriptOutcome.detail,
      segmentCount: transcriptOutcome.segments.length,
      samples: transcriptOutcome.segments
        .slice(0, 3)
        .map((segment) => ({
          startSeconds: segment.startSeconds,
          text: segment.text,
        })),
      language: transcriptOutcome.language,
      isAutoGenerated: transcriptOutcome.isAutoGenerated,
    };

    const botBlocked =
      watchStep.playabilityStatus === "LOGIN_REQUIRED" ||
      (watchStep.playabilityReason ?? "").toLowerCase().includes("bot");
    const fullyOperational =
      searchStep.ok && watchStep.ok && transcriptStep.ok && !botBlocked;

    const verdict = [
      fullyOperational
        ? "UNOFFICIAL PATH OPERATIONAL"
        : "UNOFFICIAL PATH DEGRADED/BLOCKED",
      `egress=${egressIp ?? "unknown"}`,
      `search: ${
        searchStep.ok
          ? `OK ${searchStep.resultCount} hits in ${searchStep.latencyMs}ms`
          : `FAILED (${searchStep.detail ?? "unknown"})`
      }`,
      `watch page: ${
        watchStep.ok
          ? `OK ${watchStep.playabilityStatus ?? "?"} in ${watchStep.latencyMs}ms`
          : `FAILED (${watchStep.detail ?? "unknown"})`
      }`,
      `transcript: ${
        transcriptStep.ok
          ? `OK ${transcriptStep.segmentCount} segments in ${transcriptStep.latencyMs}ms`
          : `FAILED (${transcriptStep.detail ?? "unknown"})`
      }`,
    ].join(" — ");

    return {
      ranAt,
      egressIp,
      search: searchStep,
      watchPage: watchStep,
      transcript: {
        ...transcriptStep,
        videoId: targetVideoId,
      },
      verdict,
    };
  };
