import z from "zod";

// ---- probe (deployment-time diagnostic, not called by the app) ----

export const ProbeYouTubeAccessInput = z.object({
  query: z.string().trim().min(1).max(200).default("javascript closures explained"),
  /** Probe this exact video for watch-page + transcript access; defaults to a canonical public video. */
  videoId: z
    .string()
    .trim()
    .regex(/^[\w-]{11}$/, "videoId must be an 11-character YouTube id")
    .optional(),
});

export const ProbeStep = z.object({
  ok: z.boolean(),
  latencyMs: z.number().int().nonnegative(),
  httpStatus: z.number().int().nullable(),
  detail: z.string().nullable(),
});

export const ProbeSearchHit = z.object({
  videoId: z.string(),
  title: z.string(),
  channel: z.string(),
  durationSeconds: z.number().int().nullable(),
  viewCountText: z.string().nullable(),
});

export const ProbeYouTubeAccessOutput = z.object({
  ranAt: z.date(),
  egressIp: z.string().nullable(),
  search: ProbeStep.extend({
    query: z.string(),
    resultCount: z.number().int(),
    topResults: z.array(ProbeSearchHit).max(10),
  }),
  watchPage: ProbeStep.extend({
    videoId: z.string(),
    playabilityStatus: z.string().nullable(),
    playabilityReason: z.string().nullable(),
    title: z.string().nullable(),
    durationSeconds: z.number().int().nullable(),
  }),
  transcript: ProbeStep.extend({
    videoId: z.string(),
    language: z.string().nullable(),
    isAutoGenerated: z.boolean().nullable(),
    segmentCount: z.number().int(),
    samples: z
      .array(z.object({ startSeconds: z.number(), text: z.string() }))
      .max(3),
  }),
  verdict: z.string(),
});

// ---- recommendations (skill-level, whole videos) ----

export const SkillRecommendationsInput = z.object({
  skillId: z.number().int(),
});

export const RecommendationVideo = z.object({
  videoId: z.string(),
  title: z.string(),
  channel: z.string(),
  durationSeconds: z.number().int().nullable(),
  rank: z.number().int(),
});

export const SkillRecommendationsOutput = z.object({
  status: z.enum(["PENDING", "READY", "FAILED"]),
  videos: z.array(RecommendationVideo),
});

export const RefreshRecommendationsInput = z.object({
  skillId: z.number().int(),
});

export const RefreshRecommendationsOutput = z.object({
  status: z.enum(["PENDING", "READY", "FAILED"]),
});

// ---- sponsor segments (SponsorBlock, read-only) ----

export const SponsorSegmentsInput = z.object({
  videoId: z.string().regex(/^[\w-]{11}$/),
});

export const SponsorSegmentsOutput = z.object({
  segments: z.array(
    z.object({
      startSeconds: z.number(),
      endSeconds: z.number(),
      category: z.string(),
    }),
  ),
});
